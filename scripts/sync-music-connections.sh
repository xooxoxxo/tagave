#!/usr/bin/env bash
# Regenerate packages/music-connections from one tag of the music-connections
# repository, the single source of that package until it is published to npm.
# Nothing in packages/music-connections is edited by hand: change the
# repository, tag a release there, and run this again.
#
# usage: scripts/sync-music-connections.sh <path-or-url> <tag>
#   <path-or-url>  a local checkout or a git URL of the music-connections repository
#   <tag>          a release tag, e.g. v0.2.0; it must match the package.json version
#
# MC_VENDOR_DIR overrides the target directory (the script's own test uses it).
set -euo pipefail

SRC="${1:-}"
TAG="${2:-}"
if [ -z "$SRC" ] || [ -z "$TAG" ]; then
  echo "usage: sync-music-connections.sh <path-or-url> <tag>" >&2
  exit 1
fi

ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
DEST="${MC_VENDOR_DIR:-$ROOT/packages/music-connections}"
# What the package needs to build and test; dist is built by `pnpm -r build`.
FILES=(src test package.json tsconfig.json tsconfig.test.json vitest.config.ts README.md CHANGELOG.md LICENSE)

TMP="$(mktemp -d)"
trap 'rm -rf "$TMP"' EXIT

if ! git clone --quiet --no-checkout -- "$SRC" "$TMP/repo"; then
  echo "sync-music-connections: cannot clone $SRC" >&2
  exit 1
fi
if ! git -C "$TMP/repo" -c advice.detachedHead=false checkout --quiet "refs/tags/$TAG" 2>/dev/null; then
  echo "sync-music-connections: no tag '$TAG' in $SRC" >&2
  exit 1
fi
COMMIT="$(git -C "$TMP/repo" rev-parse HEAD)"
VERSION="$(node -p 'require(process.argv[1]).version' "$TMP/repo/package.json")"
if [ "${TAG#v}" != "$VERSION" ]; then
  echo "sync-music-connections: tag '$TAG' does not match package.json version '$VERSION'" >&2
  exit 1
fi
for f in "${FILES[@]}"; do
  if [ ! -e "$TMP/repo/$f" ]; then
    echo "sync-music-connections: $f is missing at $TAG" >&2
    exit 1
  fi
done

# The delete below must only ever hit a vendor folder. Refuse anything else:
# the filesystem root, the home directory, or a directory that is neither
# named music-connections, empty, nor already a vendored copy (VENDORED.md).
mkdir -p "$DEST"
DEST_REAL="$(cd "$DEST" && pwd -P)"
if [ "$DEST_REAL" = "/" ] || [ "$DEST_REAL" = "$(cd "$HOME" && pwd -P)" ]; then
  echo "sync-music-connections: refusing to clear $DEST_REAL" >&2
  exit 1
fi
if [ "$(basename "$DEST_REAL")" != "music-connections" ] \
  && [ -n "$(ls -A "$DEST_REAL")" ] \
  && [ ! -e "$DEST_REAL/VENDORED.md" ]; then
  echo "sync-music-connections: $DEST_REAL is not a vendor folder (not named music-connections, not empty, no VENDORED.md); refusing to clear it" >&2
  exit 1
fi

# Replace everything except the installed node_modules.
find "$DEST" -mindepth 1 -maxdepth 1 ! -name node_modules -exec rm -rf {} +
for f in "${FILES[@]}"; do
  cp -R "$TMP/repo/$f" "$DEST/"
done

# sha256 over the sorted "sha256  relative-path" lines of every file copied
# (packages/core/src/mc/vendored.test.ts recomputes it the same way).
CONTENT="$(cd "$DEST" && node -e '
const { createHash } = require("node:crypto");
const { readFileSync, readdirSync, statSync } = require("node:fs");
const lines = [];
const walk = (p) => {
  if (statSync(p).isDirectory()) for (const e of readdirSync(p)) walk(p + "/" + e);
  else lines.push(createHash("sha256").update(readFileSync(p)).digest("hex") + "  " + p);
};
for (const f of process.argv.slice(1)) walk(f);
lines.sort();
process.stdout.write(createHash("sha256").update(lines.join("\n") + "\n").digest("hex"));
' "${FILES[@]}")"

# Name a URL without any credentials in it; never write a local path into the repo.
case "$SRC" in
  *://* | git@*) ORIGIN="$(printf '%s' "$SRC" | sed -E 's#^([A-Za-z][A-Za-z0-9+.-]*://)[^/@]*@#\1#')" ;;
  *) ORIGIN="the music-connections repository (a local checkout: not published yet)" ;;
esac

BT='`'
COPIED=""
for f in "${FILES[@]}"; do COPIED="${COPIED:+$COPIED, }$BT$f$BT"; done

{
  echo "# Vendored: music-connections"
  echo
  echo "Generated by \`scripts/sync-music-connections.sh\`. Do not edit anything in this"
  echo "directory by hand: change the music-connections repository, tag a release"
  echo "there, and run the script again with the new tag."
  echo
  echo "- Source: $ORIGIN"
  echo "- Tag: $TAG"
  echo "- Commit: $COMMIT"
  echo "- Copied: $COPIED"
  echo "- Content: sha256:$CONTENT"
  echo "- License: MIT (\`LICENSE\`)"
  echo
  echo "The music-connections repository at this tag is the single source of these"
  echo "files. @tagave/core checks that the tag above matches \`package.json\` and"
  echo "that the content hash matches the files (packages/core/src/mc/vendored.test.ts)."
  echo
  echo "Once the package is published to npm, depend on \`music-connections\` at"
  echo "this version instead and delete this directory."
} > "$DEST/VENDORED.md"

echo "sync-music-connections: packages/music-connections is now $TAG ($COMMIT)"
